"""One-off Phase 1 spike: measure TMDB Hebrew coverage and record test fixtures.

Not imported by the app. Needs only httpx. Keys are read from api/.env (TMDB_API_KEY,
OMDB_API_KEY); they are never printed or written anywhere.

    uv --directory api run python scripts/catalog_spike.py measure
    uv --directory api run python scripts/catalog_spike.py record
"""

from __future__ import annotations

import json
import re
import sys
from concurrent.futures import ThreadPoolExecutor
from datetime import date
from pathlib import Path

import httpx

API_DIR = Path(__file__).resolve().parents[1]
REPO_DIR = API_DIR.parent
FIXTURES = API_DIR / "tests" / "fixtures"
REPORT = REPO_DIR / "docs" / "superpowers" / "spikes" / "2026-11-01-tmdb-spike.md"
TMDB = "https://api.themoviedb.org/3"
OMDB = "https://www.omdbapi.com/"
HEBREW = re.compile(r"[֐-׿]")
SEVERANCE_TV_ID = 95396


def read_env() -> dict[str, str]:
    values: dict[str, str] = {}
    env_file = API_DIR / ".env"
    if env_file.exists():
        for line in env_file.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                key, _, value = line.partition("=")
                values[key.strip()] = value.strip().strip("\"'")
    return values


class Tmdb:
    def __init__(self, key: str) -> None:
        self.params: dict[str, str] = {}
        headers: dict[str, str] = {}
        if key.startswith("eyJ"):
            headers["Authorization"] = f"Bearer {key}"
        else:
            self.params["api_key"] = key
        self.http = httpx.Client(base_url=TMDB, headers=headers, timeout=15)

    def get(self, path: str, **params: str) -> dict:
        for attempt in range(4):
            r = self.http.get(path, params={**self.params, **params})
            if r.status_code == 429:
                import time

                time.sleep(2 * (attempt + 1))
                continue
            check(r, f"TMDB {path}")
            return r.json()
        raise RuntimeError(f"TMDB {path}: still rate limited")


def check(r: httpx.Response, what: str) -> None:
    # Not raise_for_status(): its message holds the URL, and the URL can hold a key.
    if r.is_error:
        sys.exit(f"{what} failed: HTTP {r.status_code}")


def pct(n: int, total: int) -> str:
    return f"{100 * n / total:.1f}% ({n}/{total})" if total else "n/a"


def he_translation(details: dict, media_type: str) -> dict:
    for entry in details.get("translations", {}).get("translations", []):
        if entry.get("iso_639_1") == "he":
            return entry.get("data") or {}
    return {}


def popular_ids(tmdb: Tmdb, kind: str, pages: int = 5) -> list[int]:
    ids: list[int] = []
    for page in range(1, pages + 1):
        ids += [
            r["id"]
            for r in tmdb.get(f"{kind}/popular", page=str(page), language="en-US")["results"]
        ]
    return ids


def measure() -> None:
    env = read_env()
    tmdb = Tmdb(env["TMDB_API_KEY"])
    lines = [
        "# TMDB spike — 2026-11-01",
        "",
        f"Generated by `api/scripts/catalog_spike.py measure` on {date.today().isoformat()}.",
        "Sample: `movie/popular` and `tv/popular`, pages 1–5 (en-US).",
        "'Hebrew' = the text has Hebrew letters (a silent English fallback does not count).",
        "",
        "| | movie | series |",
        "|---|---|---|",
    ]
    rows: dict[str, dict[str, str]] = {}
    for kind, label in (("movie", "movie"), ("tv", "series")):
        ids = popular_ids(tmdb, kind)

        def fetch(i: int, kind: str = kind) -> tuple[dict, dict]:
            a = tmdb.get(f"{kind}/{i}", language="en-US", append_to_response="translations")
            b = tmdb.get(f"{kind}/{i}", language="he-IL")
            return a, b

        with ThreadPoolExecutor(max_workers=8) as pool:
            pairs = list(pool.map(fetch, ids))
        title_key = "title" if kind == "movie" else "name"
        n = len(pairs)
        via_trans = via_il = title_trans = title_il = disagree = 0
        for en_details, he_details in pairs:
            t = he_translation(en_details, kind)
            t_over = (t.get("overview") or "").strip()
            i_over = (he_details.get("overview") or "").strip()
            has_t = bool(HEBREW.search(t_over))
            has_i = bool(HEBREW.search(i_over))
            via_trans += has_t
            via_il += has_i
            title_trans += bool(HEBREW.search(t.get(title_key) or ""))
            title_il += bool(HEBREW.search(he_details.get(title_key) or ""))
            disagree += (has_t != has_i) or (has_t and has_i and t_over != i_over)
        rows[label] = {
            "Titles sampled": str(n),
            "Hebrew overview via `translations`": pct(via_trans, n),
            "Hebrew overview via `language=he-IL`": pct(via_il, n),
            "Hebrew title via `translations`": pct(title_trans, n),
            "Hebrew title via `language=he-IL`": pct(title_il, n),
            "Titles where the two methods disagree": str(disagree),
        }
    for name in rows["movie"]:
        lines.append(f"| {name} | {rows['movie'][name]} | {rows['series'][name]} |")

    en = tmdb.get("search/multi", query="The Odyssey", language="en-US", include_adult="false")
    he = tmdb.get("search/multi", query="האודיסאה", language="he-IL", include_adult="false")
    odyssey = pick_odyssey(en)
    lines += ["", "## Hebrew search", ""]
    if odyssey is None:
        lines.append("The English search did not return a 2026 *The Odyssey*.")
    else:
        rank = next(
            (n for n, r in enumerate(he["results"], 1) if r.get("id") == odyssey["id"]), None
        )
        lines.append(
            f"2026 *The Odyssey* is TMDB movie {odyssey['id']}. "
            + (
                f"The Hebrew query `האודיסאה` finds it at rank {rank} of {len(he['results'])}."
                if rank
                else f"The Hebrew query `האודיסאה` does NOT find it ({len(he['results'])} results)."
            )
        )
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"\nwrote {REPORT}")


def pick_odyssey(search: dict) -> dict | None:
    hits = [
        r
        for r in search.get("results", [])
        if r.get("media_type") == "movie"
        and (r.get("title") or "") == "The Odyssey"
        and (r.get("release_date") or "").startswith("2026")
    ]
    return max(hits, key=lambda r: r.get("popularity", 0)) if hits else None


def dump(path: str, body: dict, keys: list[str]) -> None:
    text = json.dumps(body, ensure_ascii=False, indent=2) + "\n"
    for key in keys:
        if key and key in text:
            print(f"refusing to write {path}: body contains an API key", file=sys.stderr)
            sys.exit(1)
    target = FIXTURES / f"{path}.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target.relative_to(REPO_DIR)}")


def record() -> None:
    env = read_env()
    tmdb = Tmdb(env["TMDB_API_KEY"])
    keys = [env.get("TMDB_API_KEY", ""), env.get("OMDB_API_KEY", "")]
    omdb_key = env["OMDB_API_KEY"]

    search_en = tmdb.get(
        "search/multi", query="The Odyssey", language="en-US", include_adult="false"
    )
    dump("tmdb/search_odyssey_en", search_en, keys)
    dump(
        "tmdb/search_odyssey_he",
        tmdb.get("search/multi", query="האודיסאה", language="he-IL", include_adult="false"),
        keys,
    )
    odyssey = pick_odyssey(search_en)
    if odyssey is None:
        sys.exit("no 2026 'The Odyssey' in the English search")
    append = {"language": "en-US", "append_to_response": "external_ids,translations"}
    movie = tmdb.get(f"movie/{odyssey['id']}", **append)
    dump("tmdb/movie_odyssey", movie, keys)
    dump("tmdb/tv_severance", tmdb.get(f"tv/{SEVERANCE_TV_ID}", **append), keys)

    no_hebrew = None
    for i in popular_ids(tmdb, "movie"):
        d = tmdb.get(f"movie/{i}", **append)
        t = he_translation(d, "movie")
        if not HEBREW.search(t.get("overview") or "") and d["external_ids"].get("imdb_id"):
            no_hebrew = d
            break
    if no_hebrew is None:
        sys.exit("no sampled movie without a Hebrew overview")
    dump("tmdb/movie_no_hebrew", no_hebrew, keys)

    for kind in ("movie", "tv"):
        for code, name in (("en-US", "en"), ("he-IL", "he")):
            dump(f"tmdb/genre_{kind}_{name}", tmdb.get(f"genre/{kind}/list", language=code), keys)

    omdb = httpx.Client(timeout=15)
    imdb_ids = {
        "odyssey": movie["external_ids"]["imdb_id"],
        "severance": tmdb.get(f"tv/{SEVERANCE_TV_ID}/external_ids")["imdb_id"],
        "not_found": "tt0000000",
    }
    for name, imdb_id in imdb_ids.items():
        r = omdb.get(OMDB, params={"i": imdb_id, "apikey": omdb_key})
        check(r, f"OMDb {name}")
        dump(f"omdb/{name}", r.json(), keys)
    print(
        f"TMDB ids used: odyssey={odyssey['id']} severance={SEVERANCE_TV_ID} "
        f"no_hebrew={no_hebrew['id']}"
    )


if __name__ == "__main__":
    commands = {"measure": measure, "record": record}
    if len(sys.argv) != 2 or sys.argv[1] not in commands:
        sys.exit("usage: catalog_spike.py {measure,record}")
    try:
        commands[sys.argv[1]]()
    except httpx.HTTPError as err:
        # The default traceback would print the request URL, which can hold a key.
        sys.exit(f"network error: {type(err).__name__}")
